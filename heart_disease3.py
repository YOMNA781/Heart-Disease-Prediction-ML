x_data = data.drop(['heart_disease'], axis=1)

# Convert boolean columns to numeric (0 or 1)
x_data = x_data.astype(int)

# normalization
X = (x_data - x_data.min()) / (x_data.max() - x_data.min())
y = data['heart_disease']

from sklearn.model_selection import train_test_split
X_train, X_test, y_train, y_test = train_test_split(X, y, test_size = 0.2, random_state = 0)

from sklearn.discriminant_analysis import QuadraticDiscriminantAnalysis
from sklearn.metrics import classification_report, accuracy_score

qda = QuadraticDiscriminantAnalysis()
qda.fit(X_train, y_train)

y_pred_qda = qda.predict(X_test)

print("Gaussian Classifier (QDA)")
print(classification_report(y_test, y_pred_qda))
acc_qda = accuracy_score(y_test, y_pred_qda)
print("Accuracy:", acc_qda)

X_train_class0 = X_train[y_train == 0]
X_train_class1 = X_train[y_train == 1]

cov_class0 = np.cov(X_train_class0.T)
cov_class1 = np.cov(X_train_class1.T)

print("Covariance Matrix Shape Class 0:", cov_class0.shape)
print("Covariance Matrix Shape Class 1:", cov_class1.shape)

eig_vals_0, eig_vecs_0 = np.linalg.eig(cov_class0)
eig_vals_1, eig_vecs_1 = np.linalg.eig(cov_class1)

print("Top Eigenvalues Class 0:", np.sort(eig_vals_0)[::-1][:5])
print("Top Eigenvalues Class 1:", np.sort(eig_vals_1)[::-1][:5])

from sklearn.decomposition import PCA

# -------- PCA Feature Selection --------
pca = PCA(n_components=2)
X_train_pca = pca.fit_transform(X_train)
X_test_pca = pca.transform(X_test)

print("Explained Variance Ratio:", pca.explained_variance_ratio_)

qda_pca = QuadraticDiscriminantAnalysis()
qda_pca.fit(X_train_pca, y_train)

y_pred_qda_pca = qda_pca.predict(X_test_pca)

print("Gaussian Classifier AFTER PCA")
print(classification_report(y_test, y_pred_qda_pca))
acc_qda_pca = accuracy_score(y_test, y_pred_qda_pca)
print("Accuracy:", acc_qda_pca)

from sklearn.svm import SVC

svm = SVC(kernel='rbf', gamma='scale', random_state=42)
svm.fit(X_train, y_train)

y_pred_svm = svm.predict(X_test)

print("SVM Classifier (Comparison)")
print(classification_report(y_test, y_pred_svm))
acc_svm = accuracy_score(y_test, y_pred_svm)
print("Accuracy:", acc_svm)

models = ['Gaussian', 'Gaussian + PCA', 'SVM']
accuracies = [acc_qda, acc_qda_pca, acc_svm]

plt.bar(models, accuracies)
